import { createHash } from 'node:crypto';

/**
 * PWA, built in: a web manifest and a service worker written at build time.
 *
 * The shape follows vite-plugin-pwa's generateSW: the worker is generated from
 * the bundle itself, so its precache list is exactly the files this build
 * emitted and its version changes whenever any of them does.
 *
 *  - **App shell, precached** — `index.html`, the hashed JS/CSS chunks, the
 *    icons, the manifest. Installed in the background on the first visit.
 *  - **Models, motions, textures, HDR — cached on use** (stale-while-
 *    revalidate): the first visit downloads them once, as it would anyway;
 *    every visit after starts from the cache, offline included, and picks up
 *    a replaced file on the next launch.
 *  - **Pages** — network first, the cached shell when offline.
 *
 * Only in a production build; `main.js` registers it only on https (or
 * localhost), which a service worker requires anyway.
 */
export function pwa({ name, shortName, description, themeColor, backgroundColor }) {
  const manifest = {
    name,
    short_name: shortName,
    description,
    lang: 'ja',
    start_url: './',
    scope: './',
    display: 'fullscreen',
    display_override: ['fullscreen', 'standalone'],
    orientation: 'landscape',
    background_color: backgroundColor,
    theme_color: themeColor,
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
    ]
  };

  return {
    name: 'samurai-pwa',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(manifest, null, 2) });
      const shell = [
        './',
        'manifest.webmanifest',
        ...manifest.icons.map((i) => i.src),
        'icons/apple-touch-icon.png',
        ...Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'sw.js' && !/\/Editor-/.test(f))
      ];
      const version = createHash('sha256').update(JSON.stringify(shell)).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker(version, [...new Set(shell)]) });
    }
  };
}

function worker(version, shell) {
  return `// Generated by build/pwa.js — do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = ${JSON.stringify(shell)};
const SHELL_CACHE = 'samurai-shell-' + VERSION;
const ASSET_CACHE = 'samurai-assets-v1';
const ASSETS = /\\/(models|animations|textures|hdri|icons)\\//;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('samurai-shell-') && k !== SHELL_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith(fetch(req).catch(() => caches.match('./', { ignoreSearch: true })));
    return;
  }
  if (ASSETS.test(url.pathname)) {
    event.respondWith(
      caches.open(ASSET_CACHE).then(async (cache) => {
        const hit = await cache.match(req);
        const refresh = fetch(req)
          .then((res) => {
            if (res.ok) cache.put(req, res.clone());
            return res;
          })
          .catch(() => hit);
        return hit || refresh;
      })
    );
    return;
  }
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
}
