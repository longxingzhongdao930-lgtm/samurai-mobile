/**
 * Upper-body motions for the weapons the clips were not made for.
 *
 * The rig only has katana clips. Each weapon here keeps a clip's footwork
 * (and its timing, its warp, its hit frames) and has its arms and torso
 * re-posed every frame by `combat/WeaponMotion.js`: these are the keys it
 * interpolates.
 *
 * A key, at `t` (the move's phase, 0..1 — the same fractions `hits` uses):
 *   r   right hand (wrist), metres in the body's frame: [right, up, forward]
 *   l   left hand, likewise (two-handed weapons put it on the shaft instead)
 *   d   where the weapon points, a direction in the same frame
 *   tw  torso turn, degrees, + to the left
 *   ln  torso lean, degrees, + forward
 * Positions are for a 1.8 m body; they scale with the shoulders.
 *
 * Every move starts and ends on the weapon's `stance`, so moves chain into
 * each other and out to the idle without a pop. Each strike key sits on its
 * move's hit frame, so the blow lands where the weapon is.
 */

